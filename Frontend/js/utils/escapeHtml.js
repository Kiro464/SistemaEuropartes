/**
 * Escapa texto antes de interpolarlo en innerHTML.
 * Úsalo para valores provenientes del API o del usuario.
 */
export function escapeHtml(value) {
    return String(value ?? '')
        .replace(/&/g, '&amp;')
        .replace(/</g, '&lt;')
        .replace(/>/g, '&gt;')
        .replace(/"/g, '&quot;')
        .replace(/'/g, '&#039;');
}
